test("Fallback URL builders encode inquiry details while preserving destination parameters", () => {
  const data: InquiryFormData = {
    name: "Vikram Mehta",
    company: "Mehta Logistics",
    email: "vikram@mehta.in",
    phone: "+91 98111 22334",
    projectType: "Business Workflow Automation",
    budget: "₹50,000 – ₹1,00,000",
    timeline: "ASAP (Within 2 weeks)",
    description: "Automate driver dispatch notifications and GPS tracking.",
    agreement: true,
  };

  const fallbackMsg = buildFallbackMessage(data);
  assert.ok(fallbackMsg.includes("Vikram Mehta"));
  assert.ok(fallbackMsg.includes("Mehta Logistics"));
  assert.ok(fallbackMsg.includes("Automate driver dispatch"));

  // WhatsApp fallback
  const waUrl = getWhatsAppFallbackUrl(data);
  assert.ok(waUrl.startsWith("https://wa.me/919667344125?text="));
  const parsedWa = new URL(waUrl);
  const textParam = parsedWa.searchParams.get("text");
  assert.ok(textParam?.includes("Vikram Mehta"));
  assert.ok(textParam?.includes("Business Workflow Automation"));

  // Email fallback
  const emailUrl = getEmailFallbackUrl(data);
  assert.ok(emailUrl.startsWith(`mailto:${CONTACT_INFO.email}?`));
  const parsedEmail = new URL(emailUrl);
  assert.equal(parsedEmail.searchParams.get("subject"), "Project Inquiry from Vikram Mehta");
  assert.ok(parsedEmail.searchParams.get("body")?.includes("Vikram Mehta"));
});

test("submitInquiry handles success, HTTP errors, network failures, and honeypots", async () => {
  const validData: InquiryFormData = {
    name: "Pooja Roy",
    email: "pooja@example.com",
    description: "E-commerce store migration.",
    agreement: true,
    company: "",
    phone: "",
    projectType: "",
    budget: "",
    timeline: "",
  };

  // 1. Success response (HTTP 200)
  let callCount = 0;
  const mockFetchSuccess: typeof fetch = async () => {
    callCount++;
    return new Response("OK", { status: 200 });
  };
  const successResult = await submitInquiry(validData, { fetchImpl: mockFetchSuccess });
  assert.equal(successResult.ok, true);
  assert.equal(callCount, 1);

  // 2. Honeypot skips actual network fetch (anti-bot silent pass)
  let botFetchCalled = false;
  const mockFetchBot: typeof fetch = async () => {
    botFetchCalled = true;
    return new Response("OK", { status: 200 });
  };
  const honeypotResult = await submitInquiry(validData, {
    honeypot: "spam-bot-value",
    fetchImpl: mockFetchBot,
  });
  assert.equal(honeypotResult.ok, true);
  assert.equal(botFetchCalled, false, "Honeypot submission must not call network");

  // 3. Non-success response (e.g. HTTP 500)
  const mockFetchError: typeof fetch = async () => {
    return new Response("Server error", { status: 500 });
  };
  const errorResult = await submitInquiry(validData, { fetchImpl: mockFetchError });
  assert.equal(errorResult.ok, false);
  assert.equal(errorResult.errorType, "http");
  assert.equal(errorResult.status, 500);
  assert.ok(errorResult.message?.includes("status 500"));

  // 4. Network failure (fetch throws TypeError)
  const mockFetchNetworkFail: typeof fetch = async () => {
    throw new TypeError("Failed to fetch");
  };
  const networkResult = await submitInquiry(validData, { fetchImpl: mockFetchNetworkFail });
  assert.equal(networkResult.ok, false);
  assert.equal(networkResult.errorType, "network");
  assert.ok(networkResult.message?.includes("connection or server error"));
});

test("submitInquiry enforces bounded timeout and avoids automatic retry", async () => {
  const validData: InquiryFormData = {
    name: "Ananya",
    email: "ananya@example.com",
    description: "Design system build.",
    agreement: true,
    company: "",
    phone: "",
    projectType: "",
    budget: "",
    timeline: "",
  };

  let attempts = 0;
  const mockFetchHanging: typeof fetch = async (_, init) => {
    attempts++;
    return new Promise((_, reject) => {
      init?.signal?.addEventListener("abort", () => {
        const abortErr = new Error("This operation was aborted");
        abortErr.name = "AbortError";
        reject(abortErr);
      });
    });
  };

  const timeoutResult = await submitInquiry(validData, {
    timeoutMs: 30, // 30ms for fast test execution
    fetchImpl: mockFetchHanging,
  });

  assert.equal(timeoutResult.ok, false);
  assert.equal(timeoutResult.errorType, "timeout");
  // Verification requirement: Explain that receipt could not be confirmed and the request may have reached us
  assert.ok(timeoutResult.message?.includes("could not confirm receipt"));
  assert.ok(timeoutResult.message?.includes("may have reached us already"));
  // Verification requirement: Do not automatically retry
  assert.equal(attempts, 1, "Must not retry timed-out requests automatically");
});
