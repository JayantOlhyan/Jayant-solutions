test("public/__forms.html registers every field generated by buildInquiryPayload", () => {
  const formsHtmlPath = path.resolve(__dirname, "../public/__forms.html");
  assert.ok(fs.existsSync(formsHtmlPath), "public/__forms.html must exist");
  const formsHtml = fs.readFileSync(formsHtmlPath, "utf8");

  // Verify form metadata
  assert.ok(formsHtml.includes('name="project-inquiry"'), "Must define project-inquiry form");
  assert.ok(formsHtml.includes('data-netlify="true"'), "Must include data-netlify attribute");
  assert.ok(formsHtml.includes('netlify-honeypot="bot-field"'), "Must configure honeypot field");

  const sampleData: InquiryFormData = {
    name: "A",
    email: "a@b.com",
    description: "C",
    agreement: true,
    company: "D",
    phone: "1",
    projectType: "Web",
    budget: "10k",
    timeline: "Now",
  };

  const payload = buildInquiryPayload(sampleData, "fake-bot");
  const registeredFields = Array.from(payload.keys());

  for (const field of registeredFields) {
    assert.ok(
      formsHtml.includes(`name="${field}"`),
      `public/__forms.html missing registered field: name="${field}"`
    );
  }
});

test("validateInquiry enforces required fields and rejects whitespace-only inputs", () => {
  // Empty data
  const emptyErrors = validateInquiry(initialInquiryData);
  assert.equal(emptyErrors.name, "Please enter your name.");
  assert.equal(emptyErrors.email, "Please enter your email address.");
  assert.equal(emptyErrors.description, "Please share a brief description of your project.");
  assert.equal(emptyErrors.agreement, "Please confirm your agreement to continue.");

  // Whitespace-only name & description
  const whitespaceErrors = validateInquiry({
    ...initialInquiryData,
    name: "   \t\n  ",
    email: "valid@example.com",
    description: "  \n  ",
    agreement: true,
  });
  assert.equal(whitespaceErrors.name, "Please enter your name.");
  assert.equal(whitespaceErrors.description, "Please share a brief description of your project.");
  assert.equal(whitespaceErrors.email, undefined);
  assert.equal(whitespaceErrors.agreement, undefined);

  // Invalid email format
  const invalidEmailErrors = validateInquiry({
    ...initialInquiryData,
    name: "Rahul",
    email: "rahul@com",
    description: "Build an MVP",
    agreement: true,
  });
  assert.ok(invalidEmailErrors.email?.includes("valid email address"));

  // Completely valid minimal inquiry (empty optional fields)
  const validErrors = validateInquiry({
    ...initialInquiryData,
    name: "Rahul Sharma",
    email: "rahul@example.com",
    description: "Need an AI-powered portal.",
    agreement: true,
  });
  assert.equal(Object.keys(validErrors).length, 0);
});

